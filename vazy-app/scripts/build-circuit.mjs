// Builds src/constants/circuit.ts: the fixed campus circuit, with each leg's real walking path baked in.
// Run: node scripts/build-circuit.mjs (only when a stop changes; the app never calls this API).
import { writeFileSync } from "node:fs";

// Stops in travel order (one-way, closes 9 -> 1), as [lng, lat].
const STOPS = [
  [2.3578988, 48.847436],
  [2.3584192, 48.8470936],
  [2.3590039, 48.847496],
  [2.3594867, 48.8469206],
  [2.3591219, 48.846497],
  [2.3586284, 48.8462817],
  [2.3582403, 48.8464854],
  [2.3578559, 48.8467724],
  [2.3573781, 48.8471016],
];

const round = ([lng, lat]) => [Number(lng.toFixed(6)), Number(lat.toFixed(6))];

const legs = [];
for (let i = 0; i < STOPS.length; i++) {
  const from = STOPS[i];
  const to = STOPS[(i + 1) % STOPS.length];
  const url = `https://routing.openstreetmap.de/routed-foot/route/v1/foot/${from.join(",")};${to.join(",")}?overview=full&geometries=geojson`;
  const res = await fetch(url, { headers: { "User-Agent": "Vazy/0.1 (circuit build script)" } });
  if (!res.ok) throw new Error(`Leg ${i + 1}: HTTP ${res.status}`);
  const json = await res.json();
  if (json.code !== "Ok") throw new Error(`Leg ${i + 1}: ${json.code}`);
  const route = json.routes[0];
  legs.push({ path: route.geometry.coordinates.map(round), distance: Math.round(route.distance) });
}

const entries = STOPS.map(
  (lngLat, i) =>
    `  { name: "Stop ${i + 1}", lngLat: ${JSON.stringify(lngLat)}, distance: ${legs[i].distance}, path: ${JSON.stringify(legs[i].path)} },`,
).join("\n");

writeFileSync(
  new URL("../src/constants/circuit.ts", import.meta.url),
  `// Generated by scripts/build-circuit.mjs from OSM foot routing; do not edit by hand.
// Each stop's \`path\`/\`distance\` (meters) is the leg to the NEXT stop; the circuit is one-way and closes last -> first.
export type LngLat = [number, number];

export type Stop = { name: string; lngLat: LngLat; distance: number; path: LngLat[] };

export const STOPS: Stop[] = [
${entries}
];
`,
);

console.log(`circuit.ts: ${STOPS.length} stops, ${legs.reduce((m, l) => m + l.distance, 0)} m`);

// Builds src/constants/circuit.ts: each leg's real walking path, keyed by the stop it starts from.
// Run: node scripts/build-circuit.mjs, only when a stop's position or the order changes in
// src/constants/stops.ts (names don't need it). The app never calls this API.
import { writeFileSync } from "node:fs";
import { STOP_DEFS } from "../src/constants/stops.ts";

const round = ([lng, lat]) => [Number(lng.toFixed(6)), Number(lat.toFixed(6))];

const legs = [];
for (let i = 0; i < STOP_DEFS.length; i++) {
  const from = STOP_DEFS[i];
  const to = STOP_DEFS[(i + 1) % STOP_DEFS.length];
  const url = `https://routing.openstreetmap.de/routed-foot/route/v1/foot/${from.lngLat.join(",")};${to.lngLat.join(",")}?overview=full&geometries=geojson`;
  const res = await fetch(url, { headers: { "User-Agent": "Vazy/0.1 (circuit build script)" } });
  if (!res.ok) throw new Error(`Leg ${from.id}: HTTP ${res.status}`);
  const json = await res.json();
  if (json.code !== "Ok") throw new Error(`Leg ${from.id}: ${json.code}`);
  const route = json.routes[0];
  legs.push(
    `  ${JSON.stringify(from.id)}: { distance: ${Math.round(route.distance)}, path: ${JSON.stringify(route.geometry.coordinates.map(round))} },`,
  );
}

writeFileSync(
  new URL("../src/constants/circuit.ts", import.meta.url),
  `// Generated by scripts/build-circuit.mjs from OSM foot routing; do not edit by hand.
// Edit names in ./stops.ts; each leg below is the path (meters) from that stop to the NEXT one.
import { type LngLat, STOP_DEFS, type StopDef } from "./stops.ts";

export type { LngLat };

export type Stop = StopDef & { distance: number; path: LngLat[] };

const LEGS: Record<string, { distance: number; path: LngLat[] }> = {
${legs.join("\n")}
};

export const STOPS: Stop[] = STOP_DEFS.map((stop) => ({ ...stop, ...LEGS[stop.id] }));
`,
);

console.log(`circuit.ts: ${STOP_DEFS.length} legs written`);
